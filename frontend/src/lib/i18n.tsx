const dicts: Record<Lang, Partial<Record<Key, string>>> = { en, hi };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string };
const I18n = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("st_lang") as Lang) || "en");
  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang: (l) => {
        localStorage.setItem("st_lang", l);
        setLangState(l);
      },
      t: (k, vars) => {
        let s = dicts[lang][k] ?? en[k] ?? k;
        for (const [n, v] of Object.entries(vars ?? {})) s = s.replace(`{${n}}`, String(v));
        return s;
      },
    }),
    [lang],
  );
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useT = () => useContext(I18n);
