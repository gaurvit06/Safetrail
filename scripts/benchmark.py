"""Run the SPEC 10.3 benchmark: the same simulated scenario through R1-R4, every call through Prune.

    backend/.venv/bin/python scripts/benchmark.py                     # all four runs, in the SPEC order R3, R4, R2, R1
    backend/.venv/bin/python scripts/benchmark.py --runs R3,R4        # just some runs (R4 reuses R3's nonce)
    backend/.venv/bin/python scripts/benchmark.py --trips 100         # fewer trips = fewer naive packs = cheaper R1
    backend/.venv/bin/python scripts/benchmark.py --no-ai             # plumbing test with no key: templates only,
                                                                      # results go to a temp folder, never to docs/
(Windows: backend\\.venv\\Scripts\\python scripts\\benchmark.py ...)

Before a real run: raise the ops key's daily cap in the Prune dashboard for the benchmark only, then lower it again
(SPEC 10.3). R1 makes one LARGE call per trip for packs, so it is by far the most expensive run.

Writes docs/benchmark_results.json (the /benchmark page reads it) and docs/BENCHMARK.md. Uses its own database,
backend/benchmark.db, so the demo screens never show benchmark trips or incidents.
"""
import argparse
import asyncio
import datetime as dt
import json
import os
import sys
import tempfile
import uuid
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "backend"))


def parse() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="SafeTrail benchmark (SPEC 10.3)")
    ap.add_argument("--runs", default="R3,R4,R2,R1", help="comma-separated, run in this order (default R3,R4,R2,R1)")
    ap.add_argument("--trips", type=int, default=500, help="trips from the scenario to include (default 500)")
    ap.add_argument("--yes", action="store_true", help="don't ask before spending Prune credits")
    ap.add_argument("--no-ai", action="store_true", help="templates only (no key needed); writes to a temp folder")
    ap.add_argument("--out", help="folder for benchmark_results.json and BENCHMARK.md (default docs/)")
    return ap.parse_args()


ARGS = parse()
if ARGS.no_ai:  # must happen before the app reads its settings
    os.environ["PRUNE_API_KEY"] = ""
    os.environ["PRUNE_PUBLIC_API_KEY"] = ""
    os.environ["DB_PATH"] = str(Path(tempfile.mkdtemp(prefix="bench-noai-")) / "benchmark.db")
else:
    os.environ["DB_PATH"] = str(REPO / "backend" / "benchmark.db")

from sqlmodel import Session  # noqa: E402

from app import benchmark  # noqa: E402
from app.config import settings  # noqa: E402
from app.db import engine, init_db  # noqa: E402
from app.seeddata import seed_db  # noqa: E402

FMT_USD = lambda v, d=6: "n/a" if v is None else f"${v:.{d}f}"  # noqa: E731
FMT_PCT = lambda v: "n/a" if v is None else f"{v:g}%"  # noqa: E731
FMT_MS = lambda v: "n/a" if v is None else f"{v} ms"  # noqa: E731


def inr(v):
    if v is None:
        return "n/a"
    r = v * settings.usd_inr
    return f"{r * 100:.2f} paise" if r < 1 else f"₹{r:.2f}"


def markdown(res: dict) -> str:
    runs = res["runs"]
    keys = [k for k in ("R1", "R2", "R3", "R4") if k in runs]
    when = lambda ts: dt.datetime.fromtimestamp(ts, dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")  # noqa: E731
    L = ["# SafeTrail benchmark (SPEC 10.3)", "",
         f"_Generated by `scripts/benchmark.py` on {res['generated']}. Scenario: {res['scenario']['about']} "
         f"Every cost below is Prune's own figure from the stored responses; anything Prune didn't return shows as n/a._", ""]
    if res.get("no_ai"):
        L += ["> **Plumbing test with no AI** (`--no-ai`): every feature used standard text and no Prune call was made. "
              "These numbers are not a benchmark result.", ""]
    L += ["## Runs", "", "| Run | What it does | Prune run id | Finished | Trips |", "|---|---|---|---|---|"]
    for k in keys:
        r = runs[k]
        L.append(f"| {r['label']} | {r['about']} | `{r['config']}` #{r['run_id']} (nonce `{r['nonce']}`) | {when(r['completed_at'])} | {r['metrics']['trips']} |")
    rows = [("Total AI cost", lambda m: f"{FMT_USD(m['cost_usd'])} ({inr(m['cost_usd'])})"),
            ("Cost per monitored trip", lambda m: f"{FMT_USD(m['cost_per_trip_usd'], 7)} ({inr(m['cost_per_trip_usd'])})"),
            ("Cost per emergency", lambda m: f"{FMT_USD(m['cost_per_emergency_usd'], 7)} ({inr(m['cost_per_emergency_usd'])})"),
            ("AI calls (errors)", lambda m: f"{m['ok_calls']} ({m['errors']})"),
            ("Calls with a cost from Prune", lambda m: f"{m['cost_known_calls']} of {m['ok_calls']}"),
            ("Routed to a cheaper model", lambda m: FMT_PCT(m["pct_routed"])),
            ("Served from Prune's cache", lambda m: FMT_PCT(m["pct_cache"])),
            ("Escalated to LARGE", lambda m: str(m["escalations"])),
            ("Latency p50 / p95", lambda m: f"{FMT_MS(m['p50_ms'])} / {FMT_MS(m['p95_ms'])}"),
            ("Standard-text fallbacks", lambda m: f"{m['template_fallbacks']} of {m['jobs']} jobs ({FMT_PCT(m['template_rate_pct'])})"),
            ("Invented-fact rate (validator rejected the first answer)", lambda m: FMT_PCT(m["invented_fact_rate_pct"])),
            ("Count accuracy (computed, never AI)", lambda m: FMT_PCT(m["count_accuracy_pct"])),
            ("Injection notes flagged (scanner / Prune / either)",
             lambda m: f"{m['injection_caught_scanner']} / {m['injection_caught_prune']} / {FMT_PCT(m['injection_recall_pct'])} of {m['injection_notes']}"),
            ("Clean notes wrongly flagged by the scanner", lambda m: str(m["clean_notes_flagged"]))]
    L += ["", "## Results", "", "| Metric | " + " | ".join(runs[k]["label"] for k in keys) + " |",
          "|---|" + "---|" * len(keys)]
    for name, fn in rows:
        L.append(f"| {name} | " + " | ".join(fn(runs[k]["metrics"]) for k in keys) + " |")
    if "R3" in runs:
        est = runs["R3"]["metrics"]["prune_estimate_without_usd"]
        L += ["", f"**Prune estimate, list price** (R3 without Prune's optimisations, Prune's own counterfactual): {FMT_USD(est)}."]
    wf = benchmark.waterfall(runs)
    L += ["", "## Where the savings come from", ""]
    if wf:
        L += ["| Step | Cost (USD) |", "|---|---|"] + [f"| {w['step']} | {'−' if w['kind'] == 'saving' else ''}{FMT_USD(abs(w['usd']))} |" for w in wf]
    else:
        L.append("Needs measured costs from all four runs (R1-R4).")
    L += ["", "## Notes", "",
          "- Counts are computed by plain code, so count accuracy must be 100%. Anything lower is a bug, not AI error.",
          "- If R1 produced better text than R4, say so: this table measures cost, safety and accuracy, not prose quality.",
          "- Cluster summaries follow the app's refresh limits in scenario time (one per minute, at most 3 per cluster); "
          "R1 re-summarises after every SOS. Copilot is counted as one brief per incident.",
          "- Each run sends its own Prune run ids (so step and budget guards never carry over), so R4's cache hits "
          "depend on Prune's exact cache matching across run ids: see `cache_new_run` in docs/PRUNE_FIELDS.md.",
          "- The injection scanner is plain English pattern matching; Hindi and Assamese tricks rely on Prune's detection.", ""]
    return "\n".join(L)


async def main() -> int:
    keys = [k.strip().upper() for k in ARGS.runs.split(",") if k.strip()]
    bad = [k for k in keys if k not in benchmark.RUNS]
    if bad:
        print("Unknown run(s): " + ", ".join(bad) + ". Use R1, R2, R3, R4.")
        return 1
    out = Path(ARGS.out) if ARGS.out else (Path(tempfile.mkdtemp(prefix="bench-out-")) if ARGS.no_ai else REPO / "docs")
    out.mkdir(parents=True, exist_ok=True)
    results_path = out / "benchmark_results.json"
    prev = json.loads(results_path.read_text(encoding="utf-8")) if results_path.exists() else {"runs": {}}
    if prev.get("no_ai") and not ARGS.no_ai:
        prev = {"runs": {}}  # never mix template-only plumbing results with real ones

    if not ARGS.no_ai and not (settings.prune_api_key and settings.model_small and settings.model_large):
        print("Prune is not configured: set PRUNE_API_KEY, MODEL_SMALL and MODEL_LARGE in .env first")
        print("(and run scripts/prune_check.py once). For a no-cost plumbing test use --no-ai.")
        return 1

    nonces = {}
    for k in keys:
        if k == "R4":
            r3 = nonces.get("R3") or (prev["runs"].get("R3") or {}).get("nonce")
            if not r3:
                print("R4 repeats R3 with the same nonce: run R3 first (or together: --runs R3,R4).")
                return 1
            nonces[k] = r3
        else:
            nonces[k] = uuid.uuid4().hex[:10]
    trips = min(ARGS.trips, 500)
    print(f"Runs: {', '.join(keys)} · {trips} trips · models {settings.model_small} / {settings.model_large}")
    if "R1" in keys:
        print(f"R1 makes about {trips} LARGE pack calls plus LARGE calls for every other job. Raise the ops key's cap first.")
    if not ARGS.no_ai and not ARGS.yes and input("This spends Prune credits. Type yes to start: ").strip().lower() != "yes":
        print("Cancelled.")
        return 1

    init_db()
    with Session(engine) as s:
        seed_db(s)
    done = await benchmark.run_many(keys, trips_n=trips, nonces=nonces)
    runs = {**prev.get("runs", {}), **{r["key"]: r for r in done}}
    res = {"generated": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), "no_ai": ARGS.no_ai,
           "usd_inr": settings.usd_inr, "scenario": {"about": benchmark.load_scenario()[0]["about"], "trips_max": 500,
                                                     "zones": 6, "sos": 40, "groups": 9, "injection_notes": 4},
           "runs": runs, "waterfall": benchmark.waterfall(runs)}
    results_path.write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")
    (out / "BENCHMARK.md").write_text(markdown(res), encoding="utf-8")
    for r in done:
        m = r["metrics"]
        print(f"{r['key']}: {m['ok_calls']} calls, cost {FMT_USD(m['cost_usd'])}, per trip {FMT_USD(m['cost_per_trip_usd'], 7)}, "
              f"per emergency {FMT_USD(m['cost_per_emergency_usd'], 7)}, counts {FMT_PCT(m['count_accuracy_pct'])}, "
              f"templates {m['template_fallbacks']}/{m['jobs']}")
    print(f"Wrote {results_path} and {out / 'BENCHMARK.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
